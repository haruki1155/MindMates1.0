import assert from "node:assert/strict";
import {test} from "node:test";
import * as functions from "./index";
import {getFirestore, Timestamp} from "firebase-admin/firestore";

test("student appointment rescheduling exposes a trusted callable", () => {
  const callable = (functions as Record<string, unknown>).rescheduleStudentAppointment;
  assert.ok(callable, "student schedule edits require a trusted callable");
  assert.equal(typeof (callable as {run?: unknown}).run, "function");
});

test("student proposals retain the slot and agreement safely replays", async () => {
  if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error("Firestore emulator required");
  const db = getFirestore();
  const uid = "schedule-test-student";
  const id = "schedule-test-appointment";
  // Use a separate week from the staff suite's 1–21 day fixture search.
  const candidate = new Date(Date.now() + 28 * 86400000);
  while (candidate.getUTCDay() === 0 || candidate.getUTCDay() === 6) candidate.setUTCDate(candidate.getUTCDate() + 1);
  const oldAt = Date.UTC(candidate.getUTCFullYear(), candidate.getUTCMonth(), candidate.getUTCDate(), 1);
  const newAt = oldAt + 3600000;
  const appointment = db.collection("appointments").doc(id);
  const oldSlot = db.collection("appointment_slots").doc(`pacc_${oldAt}`);
  const newSlot = db.collection("appointment_slots").doc(`pacc_${newAt}`);
  const lock = db.collection("appointment_user_locks").doc(uid);
  await db.collection("pacc_availability").doc("current").set({openDays: [1, 2, 3, 4, 5], opensAt: "09:00", closesAt: "17:00", presence: "in_office", acceptsWalkIns: false, notice: "", blackoutDates: []});
  await appointment.set({userId: uid, status: "confirmed", scheduledAt: Timestamp.fromMillis(oldAt), concern: "preserved"});
  await oldSlot.set({appointmentId: id});
  await lock.set({appointmentId: id});
  const call = functions.rescheduleStudentAppointment as unknown as {run: (r: unknown) => Promise<unknown>};
  const request = {auth: {uid}, data: {appointmentId: id, expectedScheduledAt: oldAt, expectedScheduleRevision: 0, scheduledAt: newAt, requestId: "request_123456"}};
  const baseline = (functions as Record<string, unknown>).initializeAppointmentScheduleRevision as {run: (r: unknown) => Promise<unknown>};
  const staff = "schedule-test-staff";
  await db.collection("users").doc(staff).set({accessRole: "admin", name: "Staff"});
  assert.ok(baseline, "legacy revision requires explicit initialization");
  const baselineRequest = {auth: {uid: staff}, data: {appointmentId: id, expectedScheduledAt: oldAt, expectedStatus: "confirmed"}};
  await lock.delete();
  await assert.rejects(baseline.run(baselineRequest), (e: {code?: string}) => e.code === "failed-precondition");
  await lock.set({appointmentId: "other"});
  await assert.rejects(baseline.run(baselineRequest), (e: {code?: string}) => e.code === "failed-precondition");
  await lock.set({appointmentId: id});
  await oldSlot.delete();
  await assert.rejects(baseline.run(baselineRequest), (e: {code?: string}) => e.code === "failed-precondition");
  await oldSlot.set({appointmentId: id});
  await assert.rejects(baseline.run({...baselineRequest, data: {...baselineRequest.data, expectedScheduledAt: oldAt + 3600000}}), (e: {code?: string}) => e.code === "failed-precondition");
  await assert.rejects(baseline.run({...baselineRequest, data: {...baselineRequest.data, expectedStatus: "requested"}}), (e: {code?: string}) => e.code === "failed-precondition");
  await oldSlot.set({appointmentId: "foreign"});
  await assert.rejects(baseline.run({auth: {uid: staff}, data: {appointmentId: id, expectedScheduledAt: oldAt, expectedStatus: "confirmed"}}), (e: {code?: string}) => e.code === "failed-precondition");
  assert.equal((await appointment.get()).data()?.scheduleRevision, undefined);
  assert.equal((await oldSlot.get()).data()?.appointmentId, "foreign");
  await oldSlot.set({appointmentId: id});
  const initialized = await Promise.allSettled([baseline.run(baselineRequest), baseline.run(baselineRequest)]);
  assert.equal(initialized.filter((r) => r.status === "fulfilled").length, 1);
  assert.equal((await appointment.collection("history").get()).empty, true);
  assert.equal((await appointment.get()).data()?.scheduleRevision, 0);
  const assertCode = async (r: unknown, code: string) => assert.rejects(call.run(r), (e: {code?: string}) => e.code === code);
  await assertCode({...request, auth: {uid: "other"}}, "permission-denied");
  await newSlot.set({appointmentId: "other-booking"});
  await assertCode(request, "already-exists");
  assert.equal((await oldSlot.get()).data()?.appointmentId, id);
  assert.equal((await appointment.get()).data()?.status, "confirmed");
  await newSlot.delete();
  await oldSlot.set({appointmentId: "other-booking"});
  await assertCode(request, "failed-precondition");
  assert.equal((await oldSlot.get()).data()?.appointmentId, "other-booking");
  await oldSlot.set({appointmentId: id});
  await assertCode({...request, data: {...request.data, expectedScheduledAt: oldAt - 3600000}}, "aborted");
  await call.run({...request, data: {...request.data, scheduledAt: oldAt, requestId: "noop_original_schedule"}});
  assert.equal((await appointment.get()).data()?.status, "confirmed");
  await call.run(request);
  const pending = (await appointment.get()).data()!;
  assert.equal(pending.status, "confirmed");
  assert.equal(pending.scheduleRevision, 0);
  assert.equal(pending.proposalRevision, 1);
  assert.equal(pending.concern, "preserved");
  assert.equal((await oldSlot.get()).data()?.appointmentId, id);
  assert.equal((await newSlot.get()).exists, false);
  await call.run(request);
  await assertCode({...request, data: {...request.data, scheduledAt: newAt + 3600000}}, "already-exists");
  const agree = functions.changeAppointmentAgreement as unknown as {run: (r: unknown) => Promise<unknown>};
  const acceptance = {auth: {uid: staff}, data: {appointmentId: id, action: "accept", expectedScheduledAt: oldAt, expectedScheduleRevision: 0, expectedProposalRevision: 1, requestId: "staff_accept_schedule"}};
  await agree.run(acceptance);
  await agree.run(acceptance);
  assert.equal((await oldSlot.get()).exists, false);
  assert.equal((await newSlot.get()).data()?.appointmentId, id);
  assert.equal((await appointment.get()).data()?.scheduleRevision, 1);
  assert.equal((await appointment.get()).data()?.status, "confirmed");
  const edits = await Promise.allSettled([oldAt, newAt + 3600000].map((target, i) => call.run({auth: {uid}, data: {appointmentId: id, expectedScheduledAt: newAt, expectedScheduleRevision: 1, expectedProposalRevision: 2, scheduledAt: target, requestId: `race_edit_${i}`}})));
  assert.equal(edits.filter(r => r.status === "fulfilled").length, 1);
  const raced = (await appointment.get()).data()!;
  assert.equal(raced.scheduleRevision, 1);
  assert.equal(raced.proposalRevision, 3);
  assert.equal(raced.scheduledAt.toMillis(), newAt);
  assert.equal((await newSlot.get()).data()?.appointmentId, id);
  await assert.rejects(agree.run({...acceptance, data: {...acceptance.data, requestId: "stale_acceptance_2"}}), {code: "aborted"});
});

test("legacy initialization races fail closed and never reset a revision", async () => {
  if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error("Firestore emulator required");
  const db = getFirestore();
  const id = "legacy-race-appointment";
  const uid = "legacy-race-student";
  const staff = "legacy-race-staff";
  const day = new Date(Date.now() + 35 * 86400000);
  while ([0, 6].includes(day.getUTCDay())) day.setUTCDate(day.getUTCDate() + 1);
  const at = Date.UTC(day.getUTCFullYear(), day.getUTCMonth(), day.getUTCDate(), 1);
  const ref = db.doc(`appointments/${id}`);
  const slot = db.doc(`appointment_slots/pacc_${at}`);
  const lock = db.doc(`appointment_user_locks/${uid}`);
  await db.doc(`users/${staff}`).set({accessRole: "admin"});
  await ref.set({userId: uid, status: "confirmed", scheduledAt: Timestamp.fromMillis(at), concern: "history preserved"});
  await ref.collection("history").doc("historical").set({action: "rescheduled"});
  await slot.set({appointmentId: id});
  await lock.set({appointmentId: id});
  const baseline = functions.initializeAppointmentScheduleRevision as unknown as {run: (r: unknown) => Promise<unknown>};
  const edit = functions.rescheduleStudentAppointment as unknown as {run: (r: unknown) => Promise<unknown>};
  const review = functions.reviewAppointment as unknown as {run: (r: unknown) => Promise<unknown>};
  const init = {auth: {uid: staff}, data: {appointmentId: id, expectedScheduledAt: at, expectedStatus: "confirmed"}};
  const change = {auth: {uid}, data: {appointmentId: id, expectedScheduledAt: at, expectedScheduleRevision: 0, scheduledAt: at + 3600000, requestId: "legacy_race_request"}};
  const before = (await ref.get()).data();
  await assert.rejects(edit.run({...change, data: {...change.data, expectedScheduleRevision: undefined}}));
  await assert.rejects(review.run({auth: {uid: staff}, data: {appointmentId: id, action: "confirmed", reply: "Review"}}));
  assert.deepEqual((await ref.get()).data(), before);
  await slot.set({appointmentId: "foreign"});
  const foreign = (await slot.get()).data();
  await assert.rejects(baseline.run(init));
  assert.deepEqual((await ref.get()).data(), before);
  assert.deepEqual((await slot.get()).data(), foreign);
  assert.deepEqual((await lock.get()).data(), {appointmentId: id});
  assert.deepEqual((await ref.collection("history").doc("historical").get()).data(), {action: "rescheduled"});
  await slot.set({appointmentId: id});
  const race = await Promise.allSettled([baseline.run(init), edit.run(change)]);
  assert.equal(race[0].status, "fulfilled");
  if (race[1].status === "rejected") await edit.run(change);
  const revised = (await ref.get()).data()!;
  assert.equal(revised.scheduleRevision, 0);
  assert.equal(revised.proposalRevision, 1);
  assert.equal(revised.scheduledAt.toMillis(), at);
  assert.equal(revised.status, "confirmed");
  const resets = await Promise.allSettled([baseline.run(init), baseline.run(init)]);
  assert.equal(resets.filter((r) => r.status === "fulfilled").length, 0);
  assert.deepEqual((await ref.get()).data(), revised);
  assert.equal((await slot.get()).data()?.appointmentId, id);
  assert.equal((await db.doc(`appointment_slots/pacc_${at + 3600000}`).get()).exists, false);
  assert.equal((await lock.get()).data()?.appointmentId, id);
  const agree = functions.changeAppointmentAgreement as unknown as {run: (r: unknown) => Promise<unknown>};
  await agree.run({auth: {uid: staff}, data: {appointmentId: id, action: "accept", requestId: "legacy_final_accept", expectedScheduledAt: at, expectedScheduleRevision: 0, expectedProposalRevision: 1}});
  assert.equal((await ref.get()).data()?.status, "confirmed");
});
